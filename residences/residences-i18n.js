let residenceLanguage = "fa";


function setResidenceLanguage(language) {
  if (!RESIDENCE_I18N[language]) {
    language = "fa";
  }

  residenceLanguage = language;

  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "rtl";

  return RESIDENCE_I18N[language];
}


function residenceText(key) {
  const current = RESIDENCE_I18N[residenceLanguage] || RESIDENCE_I18N.fa;

  return current[key] ?? RESIDENCE_I18N.fa[key] ?? key;
}


function getResidenceLanguage() {
  return residenceLanguage;
}
